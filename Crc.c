/**
 * \brief Resets calculation unit - data register is loaded with the initial value.
 *
 * Shall be called before every new calculation. Clears \ref CRC_TRANSFER_ERROR
 * state of a failed non-blocking calculation.
 *
 * \pre   Peripheral shall be initialized and active, no non-blocking calculation
 *        may be running; otherwise \ref CRC_REQUEST_ERROR.
 *
 * \param crcId [in]: CRC peripheral identification, value from \ref crc_PeriphId_t
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Set_Reset( crc_PeriphId_t crcId )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    retState = Crc_Check_Access( crcId, CRC_FUNCTION_ACTIVE );

    if( CRC_REQUEST_OK == retState )
    {
        /* Reset bit is cleared by HW, it can not be verified by read-back */
        LL_CRC_ResetCRCCalculationUnit( crc_PeriphConf[ crcId ].PeriphReg );

        crc_PeriphContext[ crcId ].XferState = CRC_TRANSFER_IDLE;
    }
    else
    {
        /* Peripheral is not accessible */
    }

    return ( retState );
}


/**
 * \brief Feeds data to the calculation unit (blocking, item by item).
 *
 * Calculation continues from the current CRC value, so data can be fed in more
 * parts. Use \ref Crc_Set_Reset to start a new calculation. Data items of the
 * configured input data size are assembled from bytes (little endian), data
 * need not be aligned.
 *
 * \pre   Peripheral shall be initialized and active, no non-blocking calculation
 *        may be running or failed; dataCnt shall be a multiple of the input data
 *        item size; otherwise \ref CRC_REQUEST_ERROR and nothing is fed.
 *
 * \param crcId   [in]: CRC peripheral identification, value from \ref crc_PeriphId_t
 * \param data    [in]: Pointer to data. Must not be NULL.
 * \param dataCnt [in]: Count of data bytes (0 - nothing is fed)
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Set_Data( crc_PeriphId_t crcId, const crc_DataByte_t * const data, crc_DataCnt_t dataCnt )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    retState = Crc_Check_Access( crcId, CRC_FUNCTION_INACTIVE );

    if( CRC_REQUEST_OK == retState )
    {
        retState = Crc_Check_DataCnt( crcId, dataCnt );
    }
    else
    {
        /* Peripheral is not accessible */
    }

    if( ( CRC_REQUEST_OK == retState ) &&
        ( CRC_NULL_PTR   != data     )    )
    {
        Crc_Set_DataItems( crcId, data, dataCnt );
    }
    else
    {
        /* Peripheral is not accessible or invalid data */
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Reads the current CRC value (result of the data fed since the last reset).
 *
 * Value is masked by the configured polynomial size.
 *
 * \pre   Peripheral shall be initialized and active, no non-blocking calculation
 *        may be running or failed; otherwise \ref CRC_REQUEST_ERROR.
 *
 * \param crcId     [in]: CRC peripheral identification, value from \ref crc_PeriphId_t
 * \param crcValue [out]: Pointer to store the CRC value. Must not be NULL.
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Get_Data( crc_PeriphId_t crcId, crc_Data_t * const crcValue )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;
    crc_DataSize_t     polySize = CRC_DATA_SIZE_CNT;

    retState = Crc_Check_Access( crcId, CRC_FUNCTION_INACTIVE );

    if( ( CRC_REQUEST_OK == retState ) &&
        ( CRC_NULL_PTR   != crcValue )    )
    {
        retState = Crc_Get_PolySizeId( crcId, &polySize );

        if( CRC_REQUEST_OK == retState )
        {
            *crcValue = LL_CRC_ReadData32( crc_PeriphConf[ crcId ].PeriphReg ) & crc_PolySizeLut[ polySize ].Mask;
        }
        else
        {
            /* Unknown polynomial size register value */
        }
    }
    else
    {
        /* Peripheral is not accessible or invalid pointer */
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Calculates CRC of one data block (blocking) - reset, data feed and result read.
 *
 * \pre   See \ref Crc_Set_Reset, \ref Crc_Set_Data and \ref Crc_Get_Data.
 *
 * \param crcId     [in]: CRC peripheral identification, value from \ref crc_PeriphId_t
 * \param data      [in]: Pointer to data. Must not be NULL.
 * \param dataCnt   [in]: Count of data bytes
 * \param crcValue [out]: Pointer to store the CRC value. Must not be NULL.
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Calc_Block( crc_PeriphId_t crcId, const crc_DataByte_t * const data, crc_DataCnt_t dataCnt, crc_Data_t * const crcValue )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( ( CRC_NULL_PTR != data     ) &&
        ( CRC_NULL_PTR != crcValue )    )
    {
        retState = Crc_Set_Reset( crcId );

        if( CRC_REQUEST_OK == retState )
        {
            retState = Crc_Set_Data( crcId, data, dataCnt );
        }
        else
        {
            /* Calculation unit could not be reset */
        }

        if( CRC_REQUEST_OK == retState )
        {
            retState = Crc_Get_Data( crcId, crcValue );
        }
        else
        {
            /* Data could not be fed */
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}

