/**
 * \author Mr.Nobody
 * \file Crc.c
 * \ingroup Crc
 * \brief Crc module common functionality
 *
 * STM32F4 CRC calculation unit computes CRC-32 (fixed polynomial 0x04C11DB7) of
 * 32-bit words written to the data register, the data register is reset to
 * 0xFFFFFFFF. The module provides the same functionality as CRC units with
 * programmable initial value and bit order, missing HW features are emulated:
 * - Initial value - after reset of the calculation unit one pre-load word is
 *   written, so the data register contains the requested initial value (the
 *   32-bit CRC step is invertible, see \ref Crc_Set_State).
 * - Input / output bit order - bits are reversed by CPU before the data
 *   register write / after the data register read.
 * - 8-bit and 16-bit input items - items are grouped to 32-bit words (first item
 *   in the most significant bits), remaining items at the end of the data are
 *   calculated by SW and the result is loaded to the data register.
 *
 * Data buffer is processed as an array of items of configured input data size
 * (native little endian memory order), every item is processed most significant
 * bit first:
 * - Blocking calculation - data are written by CPU (\ref Crc_Set_Data,
 *   \ref Crc_Calc_Block). Items are assembled from bytes, data need not be aligned.
 * - Non-blocking calculation - data are written by DMA2 stream in memory to
 *   memory mode (\ref Crc_Set_TransferStart). Only 32-bit items without input
 *   bit reversal are supported (data written unchanged by DMA), data shall be
 *   word aligned. End and half of the transfer and DMA transfer error are
 *   reported by user callbacks from DMA interrupt.
 *
 * Polynomial and its size can not be changed (only CRC-32 polynomial is
 * accepted). Final XOR of the result (e.g. standard CRC-32) is not supported by
 * HW and has to be done by the application.
 *
 * DMA callbacks have no parameter, so every peripheral has its own set of
 * handlers generated by CRC_DMA_DEFINE_HANDLERS().
 *
 */
