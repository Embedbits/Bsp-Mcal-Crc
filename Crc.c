/**
 * \author Mr.Nobody
 * \file Crc.c
 * \ingroup Crc
 * \brief Crc module common functionality
 *
 * CRC calculation unit computes CRC of data written to the data register with
 * programmable polynomial (7, 8, 16 or 32 bits), initial value and input / output
 * bit order. Data buffer is processed as an array of items of configured input
 * data size (8, 16 or 32 bits, native little endian memory order), every item is
 * written to the data register by one access of the same width:
 * - Blocking calculation - data are written by CPU (\ref Crc_Set_Data,
 *   \ref Crc_Calc_Block). Items are assembled from bytes, data need not be aligned.
 * - Non-blocking calculation - data are written by GPDMA channel in memory to
 *   memory mode (software request, \ref Crc_Set_TransferStart). Data shall be
 *   aligned to the item size. End and half of the transfer and GPDMA errors are
 *   reported by user callbacks from GPDMA interrupt.
 *
 * Final XOR of the result (e.g. standard CRC-32) is not supported by HW and has
 * to be done by the application.
 *
 * CRC registers are updated immediately by the AHB write (no synchronization),
 * every configuration write is therefore verified by a single read-back.
 * Exceptions: reset bit (CR.RESET, cleared by HW) and data register (write
 * feeds the calculation, read returns the result) are not verified.
 *
 * GPDMA callbacks have no parameter, so every peripheral has its own set of
 * handlers generated by CRC_DMA_DEFINE_HANDLERS().
 *
 */
