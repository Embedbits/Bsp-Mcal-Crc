/**
 * \brief Declares GPDMA handlers of one CRC peripheral
 *
 * \param name [in]: Peripheral name used in handler names (e.g. Crc1)
 */
#define CRC_DMA_DECLARE_HANDLERS( name )                                                \
    static void Crc_Dma_##name##_TransferCplt ( void );                                 \
    static void Crc_Dma_##name##_HalfTransfer ( void );                                 \
    static void Crc_Dma_##name##_Error        ( gpdma_ErrorMaskId_t errorMask )

/**
 * \brief Defines GPDMA handlers of one CRC peripheral - every handler forwards the
 *        event with the peripheral identification to the common processing function
 *
 * \param name  [in]: Peripheral name used in handler names (e.g. Crc1)
 * \param crcId [in]: Peripheral identification, value from \ref crc_PeriphId_t
 */
#define CRC_DMA_DEFINE_HANDLERS( name, crcId )                                                                  \
    static void Crc_Dma_##name##_TransferCplt( void )                    { Crc_Dma_TransferCplt( crcId ); }     \
    static void Crc_Dma_##name##_HalfTransfer( void )                    { Crc_Dma_HalfTransfer( crcId ); }     \
    static void Crc_Dma_##name##_Error( gpdma_ErrorMaskId_t errorMask )  { Crc_Dma_Error( crcId, errorMask ); }

/**
 * \brief Handler table entry of one CRC peripheral
 *
 * \param name [in]: Peripheral name used in handler names (e.g. Crc1)
 */
#define CRC_DMA_ISR_CONFIG( name )                                                      \
    { .TransferCpltIsr = Crc_Dma_##name##_TransferCplt,                                 \
      .HalfTransferIsr = Crc_Dma_##name##_HalfTransfer,                                 \
      .ErrorIsr        = Crc_Dma_##name##_Error }

