/**
 * \brief Starts non-blocking calculation - data are fed to the calculation unit
 *        by GPDMA channel (one access of the input data size per item).
 *
 * Calculation continues from the current CRC value (see \ref Crc_Set_Reset).
 * End of the transfer is signaled by \ref Crc_Get_TransferState and by transfer
 * complete callback (if active), then the result is read by \ref Crc_Get_Data.
 *
 * \note  Data buffer must stay valid and unchanged until the end of the transfer
 *        and must be accessible by GPDMA.
 *
 * \pre   Peripheral shall be initialized with \ref crc_Config_t::DmaState active,
 *        active, no calculation may be running or failed; dataCnt shall be
 *        1 - \ref CRC_TRANSFER_DATA_CNT_MAX and a multiple of the input data item
 *        size, data shall be aligned to the item size; otherwise
 *        \ref CRC_REQUEST_ERROR.
 *
 * \param crcId   [in]: CRC peripheral identification, value from \ref crc_PeriphId_t
 * \param data    [in]: Pointer to data. Must not be NULL.
 * \param dataCnt [in]: Count of data bytes
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Set_TransferStart( crc_PeriphId_t crcId, const crc_DataByte_t * const data, crc_DataCnt_t dataCnt )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    retState = Crc_Check_Access( crcId, CRC_FUNCTION_INACTIVE );

    if( CRC_REQUEST_OK == retState )
    {
        retState = Crc_Check_DataCnt( crcId, dataCnt );
    }
    else
    {
        /* Peripheral is not accessible */
    }

    if( ( CRC_REQUEST_OK             == retState                             ) &&
        ( CRC_FUNCTION_ACTIVE        == crc_PeriphContext[ crcId ].DmaState ) &&
        ( CRC_NULL_PTR               != data                                 ) &&
        ( 0u                          < dataCnt                              ) &&
        ( CRC_TRANSFER_DATA_CNT_MAX  >= dataCnt                              ) &&
        ( 0u == ( (uintptr_t)data % crc_InputSizeLut[ crc_PeriphContext[ crcId ].InputSize ].ItemSize ) ) )
    {
        const crc_DmaChannelState_t * const chState   = &crc_DmaChannelState[ crcId ];
        const gpdma_PeriphId_t              dmaPeriph = (gpdma_PeriphId_t)chState->PeriphId;
        const gpdma_ChannelId_t             dmaChan   = (gpdma_ChannelId_t)chState->ChannelId;
        const gpdma_DataSize_t              dmaSize   = crc_InputSizeLut[ crc_PeriphContext[ crcId ].InputSize ].DmaSize;
        gpdma_RequestState_t                dmaState  = GPDMA_REQUEST_ERROR;

        /* Data size is configured by every start - input data size can be changed at runtime */
        dmaState = Gpdma_Set_SourceDataSize( dmaPeriph, dmaChan, dmaSize );

        if( GPDMA_REQUEST_OK == dmaState )
        {
            dmaState = Gpdma_Set_DestinationDataSize( dmaPeriph, dmaChan, dmaSize );
        }
        else
        {
            /* Source data size configuration failed */
        }

        if( GPDMA_REQUEST_OK == dmaState )
        {
            dmaState = Gpdma_Set_BlockSize( dmaPeriph, dmaChan, (gpdma_BlockSize_t)dataCnt );
        }
        else
        {
            /* Destination data size configuration failed */
        }

        if( GPDMA_REQUEST_OK == dmaState )
        {
            dmaState = Gpdma_Set_SourceAddr( dmaPeriph, dmaChan, (gpdma_SrcAddr_t)(uintptr_t)data );
        }
        else
        {
            /* Block size configuration failed */
        }

        if( GPDMA_REQUEST_OK == dmaState )
        {
            /* Transfer complete interrupt may come immediately after channel enable */
            crc_PeriphContext[ crcId ].XferState = CRC_TRANSFER_BUSY;

            dmaState = Gpdma_Set_ChannelActive( dmaPeriph, dmaChan );

            if( GPDMA_REQUEST_OK != dmaState )
            {
                crc_PeriphContext[ crcId ].XferState = CRC_TRANSFER_IDLE;
            }
            else
            {
                /* Transfer is running */
            }
        }
        else
        {
            /* Source address configuration failed */
        }

        if( GPDMA_REQUEST_OK == dmaState )
        {
            retState = CRC_REQUEST_OK;
        }
        else
        {
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        /* Peripheral is not accessible, DMA is not configured or invalid data */
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Stops running non-blocking calculation.
 *
 * \note  The current CRC value is invalid after stop of a running transfer, call
 *        \ref Crc_Set_Reset before a new calculation.
 *
 * \pre   Peripheral shall be initialized with \ref crc_Config_t::DmaState active;
 *        otherwise \ref CRC_REQUEST_ERROR.
 *
 * \param crcId [in]: CRC peripheral identification, value from \ref crc_PeriphId_t
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems (also if no transfer was running).
 *         Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Set_TransferStop( crc_PeriphId_t crcId )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    retState = Crc_Check_Init( crcId );

    if( ( CRC_REQUEST_OK      == retState                             ) &&
        ( CRC_FUNCTION_ACTIVE == crc_PeriphContext[ crcId ].DmaState )    )
    {
        const crc_DmaChannelState_t * const chState  = &crc_DmaChannelState[ crcId ];
        const gpdma_RequestState_t          dmaState = Gpdma_Set_ChannelInactive( (gpdma_PeriphId_t)chState->PeriphId, (gpdma_ChannelId_t)chState->ChannelId );

        if( GPDMA_REQUEST_OK == dmaState )
        {
            if( CRC_TRANSFER_BUSY == crc_PeriphContext[ crcId ].XferState )
            {
                crc_PeriphContext[ crcId ].XferState = CRC_TRANSFER_IDLE;
            }
            else
            {
                /* No transfer was running, state is kept */
            }

            retState = CRC_REQUEST_OK;
        }
        else
        {
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


