/**
 * \brief Enables peripheral clock (data register is kept while the clock is
 *        disabled).
 *
 * \pre   Peripheral shall be initialized by \ref Crc_Init; otherwise \ref CRC_REQUEST_ERROR.
 *
 * \param crcId [in]: CRC peripheral identification, value from \ref crc_PeriphId_t
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Set_PeriphActive( crc_PeriphId_t crcId )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    retState = Crc_Check_Init( crcId );

    if( CRC_REQUEST_OK == retState )
    {
        const rcc_RequestState_t rccState = Rcc_Set_PeriphActive( crc_PeriphConf[ crcId ].PeriphRcc );

        if( RCC_REQUEST_OK == rccState )
        {
            crc_PeriphContext[ crcId ].ClockState = CRC_FUNCTION_ACTIVE;
            retState                              = CRC_REQUEST_OK;
        }
        else
        {
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        /* Peripheral is not initialized */
    }

    return ( retState );
}


/**
 * \brief Disables peripheral clock (power saving). Configuration and the
 *        intermediate CRC value are kept, all other services return
 *        \ref CRC_REQUEST_ERROR until \ref Crc_Set_PeriphActive.
 *
 * \pre   Peripheral shall be initialized and no non-blocking calculation may be
 *        running; otherwise \ref CRC_REQUEST_ERROR and nothing is changed.
 *
 * \param crcId [in]: CRC peripheral identification, value from \ref crc_PeriphId_t
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Set_PeriphInactive( crc_PeriphId_t crcId )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    retState = Crc_Check_Init( crcId );

    if( ( CRC_REQUEST_OK    == retState                              ) &&
        ( CRC_TRANSFER_BUSY != crc_PeriphContext[ crcId ].XferState )    )
    {
        const rcc_RequestState_t rccState = Rcc_Set_PeriphInactive( crc_PeriphConf[ crcId ].PeriphRcc );

        if( RCC_REQUEST_OK == rccState )
        {
            crc_PeriphContext[ crcId ].ClockState = CRC_FUNCTION_INACTIVE;
            retState                              = CRC_REQUEST_OK;
        }
        else
        {
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        /* Peripheral is not initialized or calculation is running */
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}

