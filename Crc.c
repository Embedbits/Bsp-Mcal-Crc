/**
 * \brief Initializes CRC peripheral.
 *
 * Running non-blocking calculation of a previous initialization is stopped,
 * the peripheral clock is enabled and the peripheral is reset, initial value and
 * data order are stored, calculation unit is set to the initial value and the
 * DMA stream is initialized (if \ref crc_Config_t::DmaState is active).
 *
 * \pre   Configuration shall be valid (peripheral, CRC-32 polynomial, supported
 *        output data order, DMA identifications); otherwise
 *        \ref CRC_REQUEST_ERROR is returned and nothing is changed.
 *
 * \param crcConfig [in]: Pointer to CRC configuration, see \ref crc_Config_t. Must not be NULL.
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Init( crc_Config_t * const crcConfig )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    retState = Crc_Check_Config( crcConfig );

    if( CRC_REQUEST_OK == retState )
    {
        const crc_PeriphId_t        crcId    = crcConfig->PeriphId;
        const rcc_PeriphId_t        rccId    = crc_PeriphConf[ crcId ].PeriphRcc;
        crc_PeriphContext_t * const context  = &crc_PeriphContext[ crcId ];
        rcc_RequestState_t          rccState = RCC_REQUEST_ERROR;

        /*------------- Data handling of previous initialization -------------*/
        context->InitState = CRC_FUNCTION_INACTIVE;

        retState = Crc_Dma_Set_ChannelOff( crcId );

        context->XferState = CRC_TRANSFER_IDLE;

        /*----------------- Peripheral clock and reset -----------------------*/
        if( CRC_REQUEST_OK == retState )
        {
            rccState = Rcc_Set_PeriphActive( rccId );

            if( RCC_REQUEST_OK == rccState )
            {
                rccState = Rcc_Set_ResetActive( rccId );
            }
            else
            {
                /* Peripheral clock activation failed */
            }

            if( RCC_REQUEST_OK == rccState )
            {
                rccState = Rcc_Set_ResetInactive( rccId );
            }
            else
            {
                /* Peripheral reset failed */
            }

            if( RCC_REQUEST_OK == rccState )
            {
                context->ClockState = CRC_FUNCTION_ACTIVE;
                retState            = CRC_REQUEST_OK;
            }
            else
            {
                retState = CRC_REQUEST_ERROR;
            }
        }
        else
        {
            /* DMA stream of previous initialization could not be released */
        }

        /*--------------------- Calculation configuration --------------------*/
        if( CRC_REQUEST_OK == retState )
        {
            context->InitValue   = crcConfig->InitValue;
            context->InputOrder  = crcConfig->InputDataOrder;
            context->OutputOrder = crcConfig->OutputDataOrder;
            context->InputSize   = crcConfig->InputDataSize;

            /* Calculation starts from the initial value */
            Crc_Set_State( crcId, crcConfig->InitValue );
        }
        else
        {
            /* Previous step failed */
        }

        /*-------------------- Non-blocking calculation ----------------------*/
        if( ( CRC_REQUEST_OK      == retState            ) &&
            ( CRC_FUNCTION_ACTIVE == crcConfig->DmaState )    )
        {
            retState = Crc_Dma_Set_ChannelInit( crcConfig );
        }
        else
        {
            /* Non-blocking calculation is not used or previous step failed */
        }

        /*------------------------- Module context ---------------------------*/
        if( CRC_REQUEST_OK == retState )
        {
            context->DmaState           = crcConfig->DmaState;
            context->TransferCpltIsr    = crcConfig->TransferCpltIsr;
            context->HalfTransferIsr    = crcConfig->HalfTransferIsr;
            context->TransferErrorIsr   = crcConfig->TransferErrorIsr;
            context->TransferCpltState  = CRC_FUNCTION_INACTIVE;
            context->HalfTransferState  = CRC_FUNCTION_INACTIVE;
            context->TransferErrorState = CRC_FUNCTION_INACTIVE;

            /* Callbacks configured by initialization are activated */
            if( CRC_NULL_PTR != crcConfig->TransferErrorIsr )
            {
                context->TransferErrorState = CRC_FUNCTION_ACTIVE;
            }
            else
            {
                /* Transfer error callback is not used */
            }

            if( CRC_NULL_PTR != crcConfig->TransferCpltIsr )
            {
                context->TransferCpltState = CRC_FUNCTION_ACTIVE;
            }
            else
            {
                /* Transfer complete callback is not used */
            }

            if( CRC_NULL_PTR != crcConfig->HalfTransferIsr )
            {
                context->HalfTransferState = CRC_FUNCTION_ACTIVE;
            }
            else
            {
                /* Half transfer callback is not used */
            }

            context->InitState = CRC_FUNCTION_ACTIVE;
        }
        else
        {
            /* Initialization failed, peripheral stays uninitialized */
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Deinitializes module Crc
 *
 * For every CRC peripheral: running non-blocking calculation is stopped, DMA
 * stream and its interrupt are disabled, peripheral is reset, its clock is
 * disabled and module context is cleared.
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Deinit( void )
{
    crc_RequestState_t retState = CRC_REQUEST_OK;

    for( crc_PeriphId_t crcId = (crc_PeriphId_t)0u; CRC_PERIPH_CNT > crcId; crcId ++ )
    {
        const rcc_PeriphId_t        rccId   = crc_PeriphConf[ crcId ].PeriphRcc;
        crc_PeriphContext_t * const context = &crc_PeriphContext[ crcId ];

        context->InitState = CRC_FUNCTION_INACTIVE;

        const crc_RequestState_t dmaState      = Crc_Dma_Set_ChannelOff( crcId );
        const rcc_RequestState_t rstActState   = Rcc_Set_ResetActive( rccId );
        const rcc_RequestState_t rstInactState = Rcc_Set_ResetInactive( rccId );
        const rcc_RequestState_t clkState      = Rcc_Set_PeriphInactive( rccId );

        context->ClockState         = CRC_FUNCTION_INACTIVE;
        context->DmaState           = CRC_FUNCTION_INACTIVE;
        context->XferState          = CRC_TRANSFER_IDLE;
        context->InitValue          = CRC_HW_RESET_VALUE;
        context->InputOrder         = CRC_DATA_ORDER_NORMAL;
        context->OutputOrder        = CRC_DATA_ORDER_NORMAL;
        context->InputSize          = CRC_INPUT_SIZE_32BITS;
        context->TransferCpltState  = CRC_FUNCTION_INACTIVE;
        context->HalfTransferState  = CRC_FUNCTION_INACTIVE;
        context->TransferCpltIsr    = CRC_NULL_PTR;
        context->HalfTransferIsr    = CRC_NULL_PTR;
        context->TransferErrorState = CRC_FUNCTION_INACTIVE;
        context->TransferErrorIsr   = CRC_NULL_PTR;

        if( ( CRC_REQUEST_OK != dmaState      ) ||
            ( RCC_REQUEST_OK != rstActState   ) ||
            ( RCC_REQUEST_OK != rstInactState ) ||
            ( RCC_REQUEST_OK != clkState      )    )
        {
            retState = CRC_REQUEST_ERROR;
        }
        else
        {
            /* Peripheral deinitialized */
        }
    }

    return ( retState );
}


