/**
 * \brief Fills configuration structure with default values.
 *
 * Default configuration is CRC-32 Ethernet (CRC-32/ISO-HDLC): polynomial
 * 0x04C11DB7, initial value 0xFFFFFFFF, input reversed by byte, output reversed,
 * 8-bit input data, non-blocking calculation disabled (DMA2 stream 0, low
 * priority), no callbacks.
 *
 * \note  Final XOR 0xFFFFFFFF of CRC-32 Ethernet has to be applied by the application.
 * \note  Non-blocking calculation requires 32-bit input data without input bit
 *        reversal, see \ref Crc_Set_TransferStart.
 *
 * \param crcConfig [out]: Pointer to store default configuration. Must not be NULL.
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Get_DefaultConfig( crc_Config_t * const crcConfig )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( CRC_NULL_PTR != crcConfig )
    {
        crcConfig->PeriphId         = (crc_PeriphId_t)0u;
        crcConfig->Polynomial       = CRC_POLYNOMIAL;
        crcConfig->PolySize         = CRC_DATA_SIZE_32BITS;
        crcConfig->InitValue        = CRC_DEFAULT_INIT_VALUE;
        crcConfig->InputDataOrder   = CRC_DATA_ORDER_REV_BYTE;
        crcConfig->OutputDataOrder  = CRC_DATA_ORDER_REV_WORD;
        crcConfig->InputDataSize    = CRC_INPUT_SIZE_8BITS;
        crcConfig->DmaState         = CRC_FUNCTION_INACTIVE;
#if defined(DMA2)
        crcConfig->DmaPeriphId      = CRC_DMA_PERIPH_2;
#endif /* DMA2 */
        crcConfig->DmaChannelId     = CRC_DMA_CHANNEL_0;
        crcConfig->DmaPriority      = CRC_DMA_PRIORITY_LOW;
        crcConfig->TransferCpltIsr  = CRC_NULL_PTR;
        crcConfig->HalfTransferIsr  = CRC_NULL_PTR;
        crcConfig->TransferErrorIsr = CRC_NULL_PTR;

        retState = CRC_REQUEST_OK;
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}

