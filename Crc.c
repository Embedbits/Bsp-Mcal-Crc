/**
 * \brief Calculates CRC of one data block (blocking) - reset, data feed and result read.
 *
 * \pre   See \ref Crc_Set_Reset, \ref Crc_Set_Data and \ref Crc_Get_Data.
 *
 * \param crcId     [in]: CRC peripheral identification, value from \ref crc_PeriphId_t
 * \param data      [in]: Pointer to data. Must not be NULL.
 * \param dataCnt   [in]: Count of data bytes
 * \param crcValue [out]: Pointer to store the CRC value. Must not be NULL.
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
crc_RequestState_t Crc_Calc_Block( crc_PeriphId_t crcId, const crc_DataByte_t * const data, crc_DataCnt_t dataCnt, crc_Data_t * const crcValue )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( ( CRC_NULL_PTR != data     ) &&
        ( CRC_NULL_PTR != crcValue )    )
    {
        retState = Crc_Set_Reset( crcId );

        if( CRC_REQUEST_OK == retState )
        {
            retState = Crc_Set_Data( crcId, data, dataCnt );
        }
        else
        {
            /* Calculation unit could not be reset */
        }

        if( CRC_REQUEST_OK == retState )
        {
            retState = Crc_Get_Data( crcId, crcValue );
        }
        else
        {
            /* Data could not be fed */
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}

