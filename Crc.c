/**
 * \brief GPDMA transfer complete processing - all data were written to the CRC
 *        data register (channel is disabled by HW at the end of the block).
 *
 * \param crcId [in]: CRC peripheral identification
 */
static void Crc_Dma_TransferCplt( crc_PeriphId_t crcId )
{
    if( CRC_PERIPH_CNT > crcId )
    {
        crc_PeriphContext_t * const context = &crc_PeriphContext[ crcId ];

        context->XferState = CRC_TRANSFER_IDLE;

        if( ( CRC_FUNCTION_ACTIVE == context->TransferCpltState ) &&
            ( CRC_NULL_PTR        != context->TransferCpltIsr   )    )
        {
            context->TransferCpltIsr();
        }
        else
        {
            /* User callback is not active */
        }
    }
    else
    {
        /* Invalid peripheral identification */
    }
}


/**
 * \brief GPDMA half transfer processing - half of the data were written to the
 *        CRC data register.
 *
 * \param crcId [in]: CRC peripheral identification
 */
static void Crc_Dma_HalfTransfer( crc_PeriphId_t crcId )
{
    if( CRC_PERIPH_CNT > crcId )
    {
        const crc_PeriphContext_t * const context = &crc_PeriphContext[ crcId ];

        if( ( CRC_FUNCTION_ACTIVE == context->HalfTransferState ) &&
            ( CRC_NULL_PTR        != context->HalfTransferIsr   )    )
        {
            context->HalfTransferIsr();
        }
        else
        {
            /* User callback is not active */
        }
    }
    else
    {
        /* Invalid peripheral identification */
    }
}


/**
 * \brief GPDMA error processing - transfer is stopped and signaled as
 *        \ref CRC_TRANSFER_ERROR (cleared by \ref Crc_Set_Reset), every reported
 *        GPDMA error bit is forwarded to the transfer error callback (if active).
 *
 * \param crcId     [in]: CRC peripheral identification
 * \param errorMask [in]: GPDMA error bit mask
 */
static void Crc_Dma_Error( crc_PeriphId_t crcId, gpdma_ErrorMaskId_t errorMask )
{
    if( CRC_PERIPH_CNT > crcId )
    {
        const crc_DmaChannelState_t * const chState = &crc_DmaChannelState[ crcId ];
        const crc_PeriphContext_t * const   context = &crc_PeriphContext[ crcId ];

        (void)Gpdma_Set_ChannelInactive( (gpdma_PeriphId_t)chState->PeriphId, (gpdma_ChannelId_t)chState->ChannelId );

        crc_PeriphContext[ crcId ].XferState = CRC_TRANSFER_ERROR;

        if( ( CRC_FUNCTION_ACTIVE == context->TransferErrorState ) &&
            ( CRC_NULL_PTR        != context->TransferErrorIsr   )    )
        {
            for( crc_XferErrorId_t errorId = CRC_XFER_ERROR_DMA_TRANSFER; CRC_XFER_ERROR_CNT > errorId; errorId ++ )
            {
                if( 0u != ( (uint32_t)errorMask & (uint32_t)crc_DmaErrorConfig[ errorId ].DmaError ) )
                {
                    context->TransferErrorIsr( crc_DmaErrorConfig[ errorId ].ErrorId );
                }
                else
                {
                    /* Error bit is not reported */
                }
            }
        }
        else
        {
            /* User callback is not active */
        }
    }
    else
    {
        /* Invalid peripheral identification */
    }
}


