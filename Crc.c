/**
 * \brief Checks CRC configuration.
 *
 * \param crcConfig [in]: Pointer to CRC configuration
 *
 * \return Returns \ref CRC_REQUEST_OK if configuration is valid. Otherwise
 *         returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Check_Config( const crc_Config_t * const crcConfig )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( CRC_NULL_PTR != crcConfig )
    {
        if( ( CRC_PERIPH_CNT                > crcConfig->PeriphId                       ) &&
            ( CRC_DATA_ORDER_CNT            > crcConfig->InputDataOrder                 ) &&
            ( CRC_DATA_ORDER_CNT            > crcConfig->OutputDataOrder                ) &&
            ( CRC_REG_UNSUPPORTED          != crc_OutputOrderLut[ crcConfig->OutputDataOrder ] ) &&
            ( CRC_INPUT_SIZE_CNT            > crcConfig->InputDataSize                  ) &&
            ( CRC_FUNCTION_ACTIVE          >= crcConfig->DmaState                       )    )
        {
            retState = Crc_Check_Polynomial( crcConfig->Polynomial, crcConfig->PolySize );
        }
        else
        {
            retState = CRC_REQUEST_ERROR;
        }

        if( ( CRC_REQUEST_OK      == retState            ) &&
            ( CRC_FUNCTION_ACTIVE == crcConfig->DmaState )    )
        {
            if( ( CRC_DMA_PERIPH_CNT           > crcConfig->DmaPeriphId           ) &&
                ( CRC_DMA_CHANNEL_CNT          > crcConfig->DmaChannelId          ) &&
                ( (uint32_t)GPDMA_PRIORITY_CNT > (uint32_t)crcConfig->DmaPriority )    )
            {
                retState = CRC_REQUEST_OK;
            }
            else
            {
                /* DMA configuration is invalid */
                retState = CRC_REQUEST_ERROR;
            }
        }
        else
        {
            /* DMA is not used or configuration is invalid */
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Checks polynomial - must be odd and fit into polynomial size.
 *
 * \param polynomial [in]: Polynomial coefficients
 * \param polySize   [in]: Polynomial size
 *
 * \return Returns \ref CRC_REQUEST_OK if polynomial is valid. Otherwise
 *         returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Check_Polynomial( crc_Data_t polynomial, crc_DataSize_t polySize )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( ( CRC_DATA_SIZE_CNT                                  > polySize   ) &&
        ( CRC_POLY_ODD_MASK                                 == ( polynomial & CRC_POLY_ODD_MASK ) ) &&
        ( 0u == ( polynomial & ~crc_PolySizeLut[ polySize ].Mask ) )             )
    {
        retState = CRC_REQUEST_OK;
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Checks the peripheral can be accessed - initialized, clock enabled and
 *        no non-blocking calculation running.
 *
 * \param crcId        [in]: CRC peripheral identification
 * \param errorAllowed [in]: \ref CRC_FUNCTION_ACTIVE if access is allowed in
 *                           \ref CRC_TRANSFER_ERROR state
 *
 * \return Returns \ref CRC_REQUEST_OK if the peripheral can be accessed.
 *         Otherwise returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Check_Access( crc_PeriphId_t crcId, crc_FunctionState_t errorAllowed )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    retState = Crc_Check_Init( crcId );

    if( CRC_REQUEST_OK == retState )
    {
        const crc_PeriphContext_t * const context = &crc_PeriphContext[ crcId ];

        if( ( CRC_FUNCTION_ACTIVE == context->ClockState                ) &&
            ( CRC_TRANSFER_BUSY   != context->XferState                 ) &&
            ( ( CRC_TRANSFER_ERROR  != context->XferState ) ||
              ( CRC_FUNCTION_ACTIVE == errorAllowed       )             )    )
        {
            retState = CRC_REQUEST_OK;
        }
        else
        {
            /* Clock is disabled or calculation is running / failed */
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        /* Peripheral is not initialized */
    }

    return ( retState );
}


/**
 * \brief Checks the peripheral identification and initialization.
 *
 * \param crcId [in]: CRC peripheral identification
 *
 * \return Returns \ref CRC_REQUEST_OK if the peripheral is initialized.
 *         Otherwise returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Check_Init( crc_PeriphId_t crcId )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( ( CRC_PERIPH_CNT      > crcId                                ) &&
        ( CRC_FUNCTION_ACTIVE == crc_PeriphContext[ crcId ].InitState )    )
    {
        retState = CRC_REQUEST_OK;
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Writes polynomial and its size, verified by read-back.
 *
 * \param crcId      [in]: CRC peripheral identification, must be valid
 * \param polynomial [in]: Polynomial coefficients
 * \param polySize   [in]: Polynomial size
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Set_PolynomialReg( crc_PeriphId_t crcId, crc_Data_t polynomial, crc_DataSize_t polySize )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    retState = Crc_Check_Polynomial( polynomial, polySize );

    if( ( CRC_REQUEST_OK == retState ) &&
        ( CRC_PERIPH_CNT  > crcId    )    )
    {
        CRC_TypeDef * const periphReg = crc_PeriphConf[ crcId ].PeriphReg;
        uint32_t            sizeReg   = 0u;
        crc_Data_t          polyReg   = 0u;

        LL_CRC_SetPolynomialSize( periphReg, crc_PolySizeLut[ polySize ].RegVal );
        LL_CRC_SetPolynomialCoef( periphReg, polynomial );

        sizeReg = LL_CRC_GetPolynomialSize( periphReg );
        polyReg = LL_CRC_GetPolynomialCoef( periphReg );

        if( ( crc_PolySizeLut[ polySize ].RegVal == sizeReg ) &&
            ( polynomial                         == polyReg )    )
        {
            retState = CRC_REQUEST_OK;
        }
        else
        {
            /* Read-back verification failed */
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Writes initial value, verified by read-back within the polynomial size.
 *
 * \param crcId     [in]: CRC peripheral identification, must be valid
 * \param initValue [in]: Initial value
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Set_InitValueReg( crc_PeriphId_t crcId, crc_Data_t initValue )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;
    crc_DataSize_t     polySize = CRC_DATA_SIZE_CNT;

    retState = Crc_Get_PolySizeId( crcId, &polySize );

    if( CRC_REQUEST_OK == retState )
    {
        CRC_TypeDef * const periphReg = crc_PeriphConf[ crcId ].PeriphReg;
        const crc_Data_t    mask      = crc_PolySizeLut[ polySize ].Mask;
        crc_Data_t          regValue  = 0u;

        LL_CRC_SetInitialData( periphReg, initValue );

        regValue = LL_CRC_GetInitialData( periphReg );

        if( ( initValue & mask ) == ( regValue & mask ) )
        {
            retState = CRC_REQUEST_OK;
        }
        else
        {
            /* Read-back verification failed */
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        /* Invalid peripheral or unknown polynomial size */
    }

    return ( retState );
}


/**
 * \brief Writes input data reverse mode, verified by read-back.
 *
 * \param crcId     [in]: CRC peripheral identification, must be valid
 * \param dataOrder [in]: Data order, value from \ref crc_DataOrder_t
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Set_InputOrderReg( crc_PeriphId_t crcId, crc_DataOrder_t dataOrder )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( ( CRC_PERIPH_CNT     > crcId     ) &&
        ( CRC_DATA_ORDER_CNT > dataOrder )    )
    {
        CRC_TypeDef * const periphReg = crc_PeriphConf[ crcId ].PeriphReg;
        uint32_t            regValue  = 0u;

        LL_CRC_SetInputDataReverseMode( periphReg, crc_InputOrderLut[ dataOrder ] );

        regValue = LL_CRC_GetInputDataReverseMode( periphReg );

        if( crc_InputOrderLut[ dataOrder ] == regValue )
        {
            retState = CRC_REQUEST_OK;
        }
        else
        {
            /* Read-back verification failed */
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Writes output data reverse mode, verified by read-back.
 *
 * \param crcId     [in]: CRC peripheral identification, must be valid
 * \param dataOrder [in]: Data order, \ref CRC_DATA_ORDER_NORMAL or \ref CRC_DATA_ORDER_REV_WORD
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Set_OutputOrderReg( crc_PeriphId_t crcId, crc_DataOrder_t dataOrder )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( ( CRC_PERIPH_CNT       > crcId                           ) &&
        ( CRC_DATA_ORDER_CNT   > dataOrder                       ) &&
        ( CRC_REG_UNSUPPORTED != crc_OutputOrderLut[ dataOrder ] )    )
    {
        CRC_TypeDef * const periphReg = crc_PeriphConf[ crcId ].PeriphReg;
        uint32_t            regValue  = 0u;

        LL_CRC_SetOutputDataReverseMode( periphReg, crc_OutputOrderLut[ dataOrder ] );

        regValue = LL_CRC_GetOutputDataReverseMode( periphReg );

        if( crc_OutputOrderLut[ dataOrder ] == regValue )
        {
            retState = CRC_REQUEST_OK;
        }
        else
        {
            /* Read-back verification failed */
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        /* Invalid peripheral or data order not supported for output data */
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Returns configured polynomial size identification.
 *
 * \param crcId     [in]: CRC peripheral identification
 * \param polySize [out]: Pointer to store the polynomial size. Must not be NULL.
 *
 * \return Returns \ref CRC_REQUEST_OK if the peripheral is active and register
 *         value is known. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Get_PolySizeId( crc_PeriphId_t crcId, crc_DataSize_t * const polySize )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( ( CRC_PERIPH_CNT       > crcId                                ) &&
        ( CRC_FUNCTION_ACTIVE == crc_PeriphContext[ crcId ].ClockState ) &&
        ( CRC_NULL_PTR        != polySize                              )    )
    {
        const uint32_t regValue = LL_CRC_GetPolynomialSize( crc_PeriphConf[ crcId ].PeriphReg );

        for( crc_DataSize_t sizeId = CRC_DATA_SIZE_7BITS; CRC_DATA_SIZE_CNT > sizeId; sizeId ++ )
        {
            if( crc_PolySizeLut[ sizeId ].RegVal == regValue )
            {
                *polySize = sizeId;
                retState  = CRC_REQUEST_OK;
                break;
            }
            else
            {
                /* Continue with next size */
            }
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Checks count of data bytes is a multiple of the input data item size.
 *
 * \param crcId   [in]: CRC peripheral identification
 * \param dataCnt [in]: Count of data bytes
 *
 * \return Returns \ref CRC_REQUEST_OK if the count is valid. Otherwise returns
 *         \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Check_DataCnt( crc_PeriphId_t crcId, crc_DataCnt_t dataCnt )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( ( CRC_PERIPH_CNT     > crcId                                ) &&
        ( CRC_INPUT_SIZE_CNT > crc_PeriphContext[ crcId ].InputSize )    )
    {
        const crc_DataCnt_t itemSize = crc_InputSizeLut[ crc_PeriphContext[ crcId ].InputSize ].ItemSize;

        if( 0u == ( dataCnt % itemSize ) )
        {
            retState = CRC_REQUEST_OK;
        }
        else
        {
            /* Incomplete data item */
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Writes data items to the data register (one access of the input data
 *        size per item, items assembled from bytes in little endian order).
 *
 * \param crcId   [in]: CRC peripheral identification, must be valid
 * \param data    [in]: Pointer to data, must not be NULL
 * \param dataCnt [in]: Count of data bytes, multiple of the item size
 */
static void Crc_Set_DataItems( crc_PeriphId_t crcId, const crc_DataByte_t * const data, crc_DataCnt_t dataCnt )
{
    CRC_TypeDef * const   periphReg = crc_PeriphConf[ crcId ].PeriphReg;
    const crc_InputSize_t inputSize = crc_PeriphContext[ crcId ].InputSize;
    const crc_DataCnt_t   itemSize  = crc_InputSizeLut[ inputSize ].ItemSize;

    for( crc_DataCnt_t dataIdx = 0u; dataCnt > dataIdx; dataIdx += itemSize )
    {
        crc_Data_t itemValue = 0u;

        for( crc_DataCnt_t byteIdx = 0u; itemSize > byteIdx; byteIdx ++ )
        {
            itemValue |= (crc_Data_t)data[ dataIdx + byteIdx ] << ( byteIdx * CRC_BITS_IN_BYTE );
        }

        if( CRC_INPUT_SIZE_32BITS == inputSize )
        {
            LL_CRC_FeedData32( periphReg, itemValue );
        }
        else if( CRC_INPUT_SIZE_16BITS == inputSize )
        {
            LL_CRC_FeedData16( periphReg, (uint16_t)itemValue );
        }
        else
        {
            LL_CRC_FeedData8( periphReg, (uint8_t)itemValue );
        }
    }
}


/**
 * \brief Initializes (or reuses) the GPDMA channel and enables its interrupt.
 *
 * Memory to memory transfer (software request): memory (increment) -> CRC data
 * register (static). Data size, source address and block size are configured
 * by every \ref Crc_Set_TransferStart. Transfer complete, half
 * transfer and error handlers are registered (user callbacks are gated by
 * the module).
 *
 * \param crcConfig [in]: Pointer to valid CRC configuration
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Dma_Set_ChannelInit( const crc_Config_t * const crcConfig )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( ( CRC_NULL_PTR   != crcConfig           ) &&
        ( CRC_PERIPH_CNT  > crcConfig->PeriphId )    )
    {
        const crc_PeriphId_t              crcId      = crcConfig->PeriphId;
        crc_DmaChannelState_t * const     chState    = &crc_DmaChannelState[ crcId ];
        const crc_DmaIsrConfig_t * const  isrConfig  = &crc_DmaIsrConfig[ crcId ];
        CRC_TypeDef * const               periphReg  = crc_PeriphConf[ crcId ].PeriphReg;
        gpdma_ConfigStruct_t              dmaConfig  = { 0u };
        gpdma_TransferConfig_t            xferConfig = { 0u };
        gpdma_RequestState_t              dmaState   = GPDMA_REQUEST_ERROR;

        /* --- Transfer parameters --- */
        xferConfig.Direction              = GPDMA_DIR_MEMORY_TO_MEMORY;
        xferConfig.EventMode              = GPDMA_TRANSFER_EVENT_BLOCK;
        xferConfig.TriggerType            = GPDMA_TRG_NOT_USED;
        xferConfig.TriggerMode            = GPDMA_TRIGGER_BLOCK;
        xferConfig.RequestSource          = CRC_DMA_REQUEST_UNUSED;
        xferConfig.RequestMode            = GPDMA_PERIPH_REQ_SINGLE;
        xferConfig.BlockSize              = 0u;
        xferConfig.BlockRepetitionCount   = 0u;
        xferConfig.SourceAddr             = 0u;
        xferConfig.SourceDataSize         = GPDMA_DATA_SIZE_8BITS;
        xferConfig.SourceBurstLength      = CRC_DMA_BURST_LEN;
        xferConfig.SourceAddrMode         = GPDMA_ADDR_INCREMENT;
        xferConfig.SourcePortId           = GPDMA_PORT_DEFAULT;
        xferConfig.SourceDataOp           = GPDMA_SRC_DATA_PRESERVE;
        xferConfig.DestinationAddr        = (gpdma_DstAddr_t)(uintptr_t)&periphReg->DR;
        xferConfig.DestinationDataSize    = GPDMA_DATA_SIZE_8BITS;
        xferConfig.DestinationBurstLength = CRC_DMA_BURST_LEN;
        xferConfig.DestinationAddrMode    = GPDMA_ADDR_STATIC;
        xferConfig.DestinationPortId      = GPDMA_PORT_DEFAULT;
        xferConfig.DestinationDataOp      = GPDMA_DEST_DATA_PRESERVE;

        dmaState = Gpdma_Get_DefaultConfig( &dmaConfig );

        dmaConfig.PeriphId            = (gpdma_PeriphId_t)crcConfig->DmaPeriphId;
        dmaConfig.ChannelId           = (gpdma_ChannelId_t)crcConfig->DmaChannelId;
        dmaConfig.ChannelPrio         = (gpdma_Priority_t)crcConfig->DmaPriority;
        dmaConfig.TransferExecMode    = GPDMA_XFER_EXEC_CONTINUOUS;
        dmaConfig.TransferConfig      = &xferConfig;
        dmaConfig.TransfersCount      = CRC_DMA_TRANSFERS_CNT;
        dmaConfig.XferListAccessMode  = GPDMA_TRANSFER_LIST_ACCESS_SINGLE;
        dmaConfig.XferList            = &crc_DmaXferList[ crcId ];
        dmaConfig.TransferLockState   = GPDMA_TRANSFER_LIST_LOCKED;
        dmaConfig.TransferCompleteIsr = isrConfig->TransferCpltIsr;
        dmaConfig.HalfTransferIsr     = isrConfig->HalfTransferIsr;
        dmaConfig.ErrorIsr            = isrConfig->ErrorIsr;
        dmaConfig.ErrorMask           = CRC_DMA_ERROR_MASK;

        /* --- GPDMA channel initialization or reuse --- */
        if( ( CRC_FUNCTION_ACTIVE     == chState->Initialized ) &&
            ( crcConfig->DmaPeriphId  == chState->PeriphId    ) &&
            ( crcConfig->DmaChannelId == chState->ChannelId   )    )
        {
            /* Channel is already configured for the peripheral - only priority is updated */
            dmaState = Gpdma_Set_Priority( dmaConfig.PeriphId, dmaConfig.ChannelId, dmaConfig.ChannelPrio );
        }
        else if( GPDMA_REQUEST_OK == dmaState )
        {
            dmaState = Gpdma_Init( &dmaConfig );

            if( GPDMA_REQUEST_OK == dmaState )
            {
                chState->Initialized = CRC_FUNCTION_ACTIVE;
                chState->PeriphId    = crcConfig->DmaPeriphId;
                chState->ChannelId   = crcConfig->DmaChannelId;
            }
            else
            {
                /* GPDMA channel initialization failed */
            }
        }
        else
        {
            /* Default configuration is not available */
        }

        /* GPDMA module does not enable the channel interrupt in NVIC by itself */
        if( GPDMA_REQUEST_OK == dmaState )
        {
            dmaState = Gpdma_Set_InterruptActive( dmaConfig.PeriphId, dmaConfig.ChannelId );
        }
        else
        {
            /* GPDMA channel configuration failed */
        }

        if( GPDMA_REQUEST_OK == dmaState )
        {
            retState = CRC_REQUEST_OK;
        }
        else
        {
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Disables the GPDMA channel and its interrupt (channel configuration is
 *        kept, see \ref Crc_Dma_Set_ChannelInit).
 *
 * \param crcId [in]: CRC peripheral identification
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems (also if no channel was initialized).
 *         Otherwise returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Dma_Set_ChannelOff( crc_PeriphId_t crcId )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( CRC_PERIPH_CNT > crcId )
    {
        const crc_DmaChannelState_t * const chState = &crc_DmaChannelState[ crcId ];

        if( CRC_FUNCTION_ACTIVE == chState->Initialized )
        {
            const gpdma_PeriphId_t  dmaPeriph = (gpdma_PeriphId_t)chState->PeriphId;
            const gpdma_ChannelId_t dmaChan   = (gpdma_ChannelId_t)chState->ChannelId;
            gpdma_RequestState_t    dmaState  = Gpdma_Set_ChannelInactive( dmaPeriph, dmaChan );

            if( GPDMA_REQUEST_OK == dmaState )
            {
                dmaState = Gpdma_Set_InterruptInactive( dmaPeriph, dmaChan );
            }
            else
            {
                /* Channel could not be disabled */
            }

            if( GPDMA_REQUEST_OK == dmaState )
            {
                retState = CRC_REQUEST_OK;
            }
            else
            {
                retState = CRC_REQUEST_ERROR;
            }
        }
        else
        {
            /* No GPDMA channel was initialized for the peripheral */
            retState = CRC_REQUEST_OK;
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}

