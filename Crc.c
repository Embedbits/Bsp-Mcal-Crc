/**
 * \brief Checks blocking data feed - count of data bytes is a multiple of the
 *        input data item size and input bit order is applicable to the item size.
 *
 * \param crcId   [in]: CRC peripheral identification
 * \param dataCnt [in]: Count of data bytes
 *
 * \return Returns \ref CRC_REQUEST_OK if the data can be fed. Otherwise returns
 *         \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Check_Feed( crc_PeriphId_t crcId, crc_DataCnt_t dataCnt )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( ( CRC_PERIPH_CNT     > crcId                                 ) &&
        ( CRC_INPUT_SIZE_CNT > crc_PeriphContext[ crcId ].InputSize  ) &&
        ( CRC_DATA_ORDER_CNT > crc_PeriphContext[ crcId ].InputOrder )    )
    {
        const crc_PeriphContext_t * const context  = &crc_PeriphContext[ crcId ];
        const crc_DataCnt_t               itemSize = crc_InputSizeLut[ context->InputSize ].ItemSize;

        if( ( 0u == ( dataCnt % itemSize ) ) &&
            ( crc_InputOrderMinSizeLut[ context->InputOrder ] <= context->InputSize ) )
        {
            retState = CRC_REQUEST_OK;
        }
        else
        {
            /* Incomplete data item or bit reversal wider than the item */
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Reverses bit order of the value by byte, half-word or word.
 *
 * \param value     [in]: Value to reverse
 * \param dataOrder [in]: Data order, value from \ref crc_DataOrder_t (NORMAL - value unchanged)
 *
 * \return Value with reversed bit order
 */
static uint32_t Crc_Get_BitReverse( uint32_t value, crc_DataOrder_t dataOrder )
{
    uint32_t retValue = value;

    if( CRC_DATA_ORDER_CNT > dataOrder )
    {
        for( uint32_t stepIdx = 0u; crc_ReverseStepsLut[ dataOrder ] > stepIdx; stepIdx ++ )
        {
            const uint32_t mask  = crc_ReverseStepLut[ stepIdx ].Mask;
            const uint32_t shift = crc_ReverseStepLut[ stepIdx ].Shift;

            retValue = ( ( retValue & mask ) << shift ) | ( ( retValue >> shift ) & mask );
        }
    }
    else
    {
        /* Invalid data order, value is not changed */
    }

    return ( retValue );
}


/**
 * \brief Returns CRC value before one 32-bit step of the calculation unit.
 *
 * One step (write of word W) is S' = f( S ^ W ), where f shifts the value 32
 * times MSB first and XORs the polynomial when MSB was set. Polynomial is odd,
 * so the LSB of every shifted value tells whether the polynomial was XORed and
 * the step can be inverted.
 *
 * \param crcValue [in]: CRC value after the step
 *
 * \return Value f^-1( crcValue )
 */
static crc_Data_t Crc_Get_StepInverse( crc_Data_t crcValue )
{
    crc_Data_t retValue = crcValue;

    for( uint32_t bitIdx = 0u; CRC_WORD_BITS > bitIdx; bitIdx ++ )
    {
        if( 0u != ( retValue & CRC_LSB_MASK ) )
        {
            retValue = ( ( retValue ^ CRC_POLYNOMIAL ) >> 1u ) | CRC_MSB_MASK;
        }
        else
        {
            retValue = retValue >> 1u;
        }
    }

    return ( retValue );
}


/**
 * \brief Calculates CRC of one data item by SW (items narrower than the data
 *        register write).
 *
 * \param crcValue [in]: Current CRC value
 * \param item     [in]: Data item (bit reversal applied)
 * \param itemBits [in]: Count of bits of the item (8 or 16)
 *
 * \return CRC value after the item
 */
static crc_Data_t Crc_Get_SwItem( crc_Data_t crcValue, uint32_t item, uint32_t itemBits )
{
    crc_Data_t retValue = crcValue ^ ( item << ( CRC_WORD_BITS - itemBits ) );

    for( uint32_t bitIdx = 0u; itemBits > bitIdx; bitIdx ++ )
    {
        if( 0u != ( retValue & CRC_MSB_MASK ) )
        {
            retValue = ( retValue << 1u ) ^ CRC_POLYNOMIAL;
        }
        else
        {
            retValue = retValue << 1u;
        }
    }

    return ( retValue );
}


/**
 * \brief Sets data register of the calculation unit to the value - unit is reset
 *        (0xFFFFFFFF) and pre-load word W = f^-1( crcValue ) ^ 0xFFFFFFFF is written
 *        (not needed for the reset value).
 *
 * \param crcId    [in]: CRC peripheral identification, must be valid
 * \param crcValue [in]: Required value of the data register
 */
static void Crc_Set_State( crc_PeriphId_t crcId, crc_Data_t crcValue )
{
    CRC_TypeDef * const periphReg = crc_PeriphConf[ crcId ].PeriphReg;

    /* Reset bit is cleared by HW, it can not be verified by read-back */
    LL_CRC_ResetCRCCalculationUnit( periphReg );

    if( CRC_HW_RESET_VALUE != crcValue )
    {
        LL_CRC_FeedData32( periphReg, Crc_Get_StepInverse( crcValue ) ^ CRC_HW_RESET_VALUE );
    }
    else
    {
        /* Data register contains the value after reset */
    }
}


/**
 * \brief Feeds data items to the calculation unit.
 *
 * Items are assembled from bytes (little endian), bit reversal is applied and
 * the items are grouped to 32-bit words (first item in the most significant
 * bits) written to the data register. Remaining items of incomplete group are
 * calculated by SW and the result is loaded to the data register.
 *
 * \param crcId   [in]: CRC peripheral identification, must be valid
 * \param data    [in]: Pointer to data, must not be NULL
 * \param dataCnt [in]: Count of data bytes, multiple of the item size
 */
static void Crc_Set_DataItems( crc_PeriphId_t crcId, const crc_DataByte_t * const data, crc_DataCnt_t dataCnt )
{
    CRC_TypeDef * const                 periphReg  = crc_PeriphConf[ crcId ].PeriphReg;
    const crc_DataOrder_t               inputOrder = crc_PeriphContext[ crcId ].InputOrder;
    const crc_InputSizeConfig_t * const sizeConfig = &crc_InputSizeLut[ crc_PeriphContext[ crcId ].InputSize ];
    const crc_DataCnt_t                 itemCnt    = dataCnt / sizeConfig->ItemSize;
    const crc_DataCnt_t                 groupedCnt = itemCnt - ( itemCnt % sizeConfig->GroupCnt );
    crc_DataCnt_t                       byteIdx    = 0u;
    crc_Data_t                          wordValue  = 0u;

    for( crc_DataCnt_t itemIdx = 0u; itemCnt > itemIdx; itemIdx ++ )
    {
        uint32_t itemValue = 0u;

        for( crc_DataCnt_t itemByte = 0u; sizeConfig->ItemSize > itemByte; itemByte ++ )
        {
            itemValue |= (uint32_t)data[ byteIdx ] << ( itemByte * CRC_BITS_IN_BYTE );
            byteIdx ++;
        }

        itemValue = Crc_Get_BitReverse( itemValue, inputOrder );

        if( groupedCnt > itemIdx )
        {
            /* Item of complete group - shifted into the data register word */
            if( CRC_WORD_BITS == sizeConfig->ItemBits )
            {
                wordValue = itemValue;
            }
            else
            {
                wordValue = ( wordValue << sizeConfig->ItemBits ) | itemValue;
            }

            if( 0u == ( ( itemIdx + 1u ) % sizeConfig->GroupCnt ) )
            {
                LL_CRC_FeedData32( periphReg, wordValue );
                wordValue = 0u;
            }
            else
            {
                /* Group is not complete */
            }
        }
        else
        {
            /* Item of incomplete group at the end of the data - calculated by SW */
            if( groupedCnt == itemIdx )
            {
                wordValue = LL_CRC_ReadData32( periphReg );
            }
            else
            {
                /* CRC value of previous item is used */
            }

            wordValue = Crc_Get_SwItem( wordValue, itemValue, sizeConfig->ItemBits );

            if( ( itemIdx + 1u ) == itemCnt )
            {
                Crc_Set_State( crcId, wordValue );
            }
            else
            {
                /* Continue with next item */
            }
        }
    }
}


/**
 * \brief Initializes the DMA stream and enables its interrupts.
 *
 * Memory to memory transfer: memory (source, increment) -> CRC data register
 * (destination, static), 32-bit data size. Source address and data count are
 * configured by every \ref Crc_Set_TransferStart. Transfer complete, half
 * transfer and error handlers are registered (user callbacks are gated by
 * the module).
 *
 * \param crcConfig [in]: Pointer to valid CRC configuration
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Dma_Set_ChannelInit( const crc_Config_t * const crcConfig )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( ( CRC_NULL_PTR   != crcConfig           ) &&
        ( CRC_PERIPH_CNT  > crcConfig->PeriphId )    )
    {
        const crc_PeriphId_t              crcId     = crcConfig->PeriphId;
        crc_DmaChannelState_t * const     chState   = &crc_DmaChannelState[ crcId ];
        const crc_DmaIsrConfig_t * const  isrConfig = &crc_DmaIsrConfig[ crcId ];
        const dma_PeriphId_t              dmaPeriph = (dma_PeriphId_t)crcConfig->DmaPeriphId;
        const dma_ChannelId_t             dmaChan   = (dma_ChannelId_t)crcConfig->DmaChannelId;
        dma_ConfigStruct_t                dmaConfig = { 0u };
        dma_RequestState_t                dmaState  = DMA_REQUEST_ERROR;

        dmaState = Dma_Get_DefaultConfig( &dmaConfig );

        dmaConfig.DmaPeriphId              = dmaPeriph;
        dmaConfig.DmaChannel               = dmaChan;
        dmaConfig.Direction                = DMA_DIR_MEMORY_TO_MEMORY;
        dmaConfig.TransferMode             = DMA_TRANSFER_MODE_NORMAL;
        dmaConfig.PeriphAddress            = 0u;
        dmaConfig.MemoryAddress            = (dma_MemoryAddr_t)(uintptr_t)&crc_PeriphConf[ crcId ].PeriphReg->DR;
        dmaConfig.PeriphAddrIncrement      = DMA_PERIPH_ADDR_INCREMENT;
        dmaConfig.MemoryAddrIncrement      = DMA_MEMORY_ADDR_STATIC;
        dmaConfig.PeriphTransferSize       = DMA_TRANSFER_SIZE_32BIT;
        dmaConfig.MemoryTransferSize       = DMA_TRANSFER_SIZE_32BIT;
        dmaConfig.DataCount                = 0u;
        dmaConfig.PeripheralReqId          = DMA_REQ_MEM2MEM;
        dmaConfig.Priority                 = (dma_Priority_t)crcConfig->DmaPriority;
        dmaConfig.TransferCompleteCallback = isrConfig->TransferCpltIsr;
        dmaConfig.HalfTransferCallback     = isrConfig->HalfTransferIsr;
        dmaConfig.TransferErrorCallback    = isrConfig->ErrorIsr;

        if( DMA_REQUEST_OK == dmaState )
        {
            dmaState = Dma_Init( &dmaConfig );
        }
        else
        {
            /* Default configuration is not available */
        }

        if( DMA_REQUEST_OK == dmaState )
        {
            chState->Initialized = CRC_FUNCTION_ACTIVE;
            chState->PeriphId    = crcConfig->DmaPeriphId;
            chState->ChannelId   = crcConfig->DmaChannelId;

            dmaState = Dma_Set_TransferCompleteIrqActive( dmaPeriph, dmaChan );
        }
        else
        {
            /* DMA stream initialization failed */
        }

        if( DMA_REQUEST_OK == dmaState )
        {
            dmaState = Dma_Set_HalfTransferIrqActive( dmaPeriph, dmaChan );
        }
        else
        {
            /* Previous step failed */
        }

        if( DMA_REQUEST_OK == dmaState )
        {
            dmaState = Dma_Set_TransferErrorIrqActive( dmaPeriph, dmaChan );
        }
        else
        {
            /* Previous step failed */
        }

        /* DMA module does not enable the stream interrupt in NVIC by itself */
        if( DMA_REQUEST_OK == dmaState )
        {
            dmaState = Dma_Set_InterruptActive( dmaPeriph, dmaChan );
        }
        else
        {
            /* Previous step failed */
        }

        if( DMA_REQUEST_OK == dmaState )
        {
            retState = CRC_REQUEST_OK;
        }
        else
        {
            retState = CRC_REQUEST_ERROR;
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Disables the DMA stream, its interrupts and NVIC interrupt line.
 *
 * \param crcId [in]: CRC peripheral identification
 *
 * \return Function processing state. Returns \ref CRC_REQUEST_OK if request
 *         was processed without problems (also if no stream was initialized).
 *         Otherwise returns \ref CRC_REQUEST_ERROR.
 */
static crc_RequestState_t Crc_Dma_Set_ChannelOff( crc_PeriphId_t crcId )
{
    crc_RequestState_t retState = CRC_REQUEST_ERROR;

    if( CRC_PERIPH_CNT > crcId )
    {
        crc_DmaChannelState_t * const chState = &crc_DmaChannelState[ crcId ];

        if( CRC_FUNCTION_ACTIVE == chState->Initialized )
        {
            const dma_PeriphId_t  dmaPeriph = (dma_PeriphId_t)chState->PeriphId;
            const dma_ChannelId_t dmaChan   = (dma_ChannelId_t)chState->ChannelId;
            dma_RequestState_t    dmaState  = Dma_Set_TransferInactive( dmaPeriph, dmaChan );

            if( DMA_REQUEST_OK == dmaState )
            {
                dmaState = Dma_Set_InterruptInactive( dmaPeriph, dmaChan );
            }
            else
            {
                /* Stream could not be disabled */
            }

            if( DMA_REQUEST_OK == dmaState )
            {
                dmaState = Dma_Set_TransferCompleteIrqInactive( dmaPeriph, dmaChan );
            }
            else
            {
                /* Previous step failed */
            }

            if( DMA_REQUEST_OK == dmaState )
            {
                dmaState = Dma_Set_HalfTransferIrqInactive( dmaPeriph, dmaChan );
            }
            else
            {
                /* Previous step failed */
            }

            if( DMA_REQUEST_OK == dmaState )
            {
                dmaState = Dma_Set_TransferErrorIrqInactive( dmaPeriph, dmaChan );
            }
            else
            {
                /* Previous step failed */
            }

            if( DMA_REQUEST_OK == dmaState )
            {
                chState->Initialized = CRC_FUNCTION_INACTIVE;
                retState             = CRC_REQUEST_OK;
            }
            else
            {
                retState = CRC_REQUEST_ERROR;
            }
        }
        else
        {
            /* No DMA stream was initialized for the peripheral */
            retState = CRC_REQUEST_OK;
        }
    }
    else
    {
        retState = CRC_REQUEST_ERROR;
    }

    return ( retState );
}

