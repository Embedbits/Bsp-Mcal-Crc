/**
 * \brief DMA transfer complete processing - all data were written to the CRC
 *        data register (stream is disabled by HW at the end of the transfer).
 *
 * \param crcId [in]: CRC peripheral identification
 */
static void Crc_Dma_TransferCplt( crc_PeriphId_t crcId )
{
    if( CRC_PERIPH_CNT > crcId )
    {
        crc_PeriphContext_t * const context = &crc_PeriphContext[ crcId ];

        context->XferState = CRC_TRANSFER_IDLE;

        if( ( CRC_FUNCTION_ACTIVE == context->TransferCpltState ) &&
            ( CRC_NULL_PTR        != context->TransferCpltIsr   )    )
        {
            context->TransferCpltIsr();
        }
        else
        {
            /* User callback is not active */
        }
    }
    else
    {
        /* Invalid peripheral identification */
    }
}


/**
 * \brief DMA half transfer processing - half of the data were written to the
 *        CRC data register.
 *
 * \param crcId [in]: CRC peripheral identification
 */
static void Crc_Dma_HalfTransfer( crc_PeriphId_t crcId )
{
    if( CRC_PERIPH_CNT > crcId )
    {
        const crc_PeriphContext_t * const context = &crc_PeriphContext[ crcId ];

        if( ( CRC_FUNCTION_ACTIVE == context->HalfTransferState ) &&
            ( CRC_NULL_PTR        != context->HalfTransferIsr   )    )
        {
            context->HalfTransferIsr();
        }
        else
        {
            /* User callback is not active */
        }
    }
    else
    {
        /* Invalid peripheral identification */
    }
}


/**
 * \brief DMA transfer error processing - transfer is stopped and signaled as
 *        \ref CRC_TRANSFER_ERROR (cleared by \ref Crc_Set_Reset), the error is
 *        forwarded to the transfer error callback (if active).
 *
 * \param crcId [in]: CRC peripheral identification
 */
static void Crc_Dma_Error( crc_PeriphId_t crcId )
{
    if( CRC_PERIPH_CNT > crcId )
    {
        const crc_DmaChannelState_t * const chState = &crc_DmaChannelState[ crcId ];
        const crc_PeriphContext_t * const   context = &crc_PeriphContext[ crcId ];

        /* Stream is disabled by HW on transfer error, flags are cleared */
        (void)Dma_Set_TransferInactive( (dma_PeriphId_t)chState->PeriphId, (dma_ChannelId_t)chState->ChannelId );

        crc_PeriphContext[ crcId ].XferState = CRC_TRANSFER_ERROR;

        if( ( CRC_FUNCTION_ACTIVE == context->TransferErrorState ) &&
            ( CRC_NULL_PTR        != context->TransferErrorIsr   )    )
        {
            context->TransferErrorIsr( CRC_XFER_ERROR_DMA_TRANSFER );
        }
        else
        {
            /* User callback is not active */
        }
    }
    else
    {
        /* Invalid peripheral identification */
    }
}


